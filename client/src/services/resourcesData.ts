export const hrdCentresForState = (state: string, mode: string = "All"): HRDCentre[] =>
  HRD_CENTRES.filter((c) => {
    const stateMatch = state === "All" || c.state === state;
    const modeMatch = mode === "All" || (mode === "e-Sanad Online" ? c.mode.includes("e-Sanad") : c.mode.includes("Physical"));
    return stateMatch && modeMatch;
  });

export const buildHRDDirectoryText = (centres: HRDCentre[], stateFilter: string = "All"): string => {
  const lines: string[] = [];
  lines.push("STUDY ABROAD CRM — STATE HRD & RAC DIRECTORY");
  lines.push("=".repeat(65));
  lines.push("Region / Filter    : " + stateFilter);
  lines.push("Total Centres      : " + centres.length);
  lines.push("Generated On       : " + new Date().toLocaleString("en-GB"));
  lines.push("Purpose            : Pre-Apostille State Educational Document Authentication");
  lines.push("");
  lines.push("CRITICAL COMPLIANCE NOTICE:");
  lines.push("- State HRD authentication is MANDATORY for Italian Embassy (Declaration of Value / CIMEA),");
  lines.push("  UAE, Kuwait, Austria, and European university degree equivalence verification.");
  lines.push("- Sub-Divisional Magistrate (SDM) is often REJECTED by Italian consulates and CIMEA for degrees.");
  lines.push("- State HRD must be completed in the state where the university/college is geographically located.");
  lines.push("- After HRD authentication on the reverse of the degree, MEA Apostille is affixed.");
  lines.push("");
  lines.push("=".repeat(65));
  lines.push("");
  centres.forEach((c, idx) => {
    lines.push("#" + (idx + 1) + ". " + c.name + " (" + c.state + " - " + c.city + ")");
    lines.push("-".repeat(50));
    lines.push("Department   : " + c.department);
    lines.push("Address      : " + c.address);
    lines.push("Officer      : " + c.officer + " (" + c.designation + ")");
    if (c.phone) lines.push("Phone        : " + c.phone);
    if (c.email) lines.push("Email        : " + c.email);
    lines.push("Website      : " + c.website);
    if (c.eSanadUrl) lines.push("e-Sanad URL  : " + c.eSanadUrl);
    lines.push("Mode         : " + c.mode);
    lines.push("Counter Hours: " + c.timings);
    lines.push("Turnaround   : " + c.processingDays);
    lines.push("Govt Fees    : " + c.fees);
    lines.push("Jurisdiction : " + c.jurisdiction);
    lines.push("Prerequisites:");
    c.prerequisites.forEach((p) => lines.push("  • " + p));
    lines.push("Instructions : " + c.instructions);
    lines.push("");
  });
  lines.push("Always verify current state counter procedures and university verification fees before visiting.");
  return lines.join("\n");
};

