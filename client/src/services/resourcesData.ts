export const categoryCounts = (category: ResourceCategory): number =>
  DOCUMENT_SAMPLES.filter((d) => d.category === category).length;

export const groupCount = (category: ResourceCategory, groupId: string): number =>
  DOCUMENT_SAMPLES.filter((d) => d.category === category && d.group === groupId).length;

export const documentsForCountry = (
  category: ResourceCategory,
  country: DestinationFilter
): DocumentSample[] =>
  DOCUMENT_SAMPLES.filter((d) => d.category === category).filter(
    (d) => country === 'All' || d.appliesTo.includes('All') || d.appliesTo.includes(country)
  );

export const embassiesForState = (state: string, country: DestinationFilter): EmbassyEntry[] =>
  EMBASSY_DIRECTORY.filter((e) => {
    const countryOk = country === 'All' || e.country === country;
    const stateOk = state === 'All' || e.states.includes(state);
    return countryOk && stateOk;
  });

export const buildSampleDocumentText = (doc: DocumentSample): string => {
  const lines: string[] = [];
  lines.push('STUDY ABROAD CRM — SAMPLE DOCUMENT REFERENCE');
  lines.push('='.repeat(60));
  lines.push('');
  lines.push(`Document          : ${doc.name}`);
  lines.push(`Category          : ${doc.category.toUpperCase()}`);
  lines.push(`Section           : ${RESOURCE_GROUPS[doc.category].find((g) => g.id === doc.group)?.label || doc.group}`);
  lines.push(`Requirement       : ${doc.requirement}`);
  lines.push(`Applies to        : ${doc.appliesTo.join(', ')}`);
  lines.push(`Issuing authority : ${doc.issuingAuthority}`);
  lines.push(`Format            : ${doc.format}`);
  lines.push(`Validity          : ${doc.validity}`);
  if (doc.processingTime) lines.push(`Processing time   : ${doc.processingTime}`);
  lines.push(`Sample file name  : ${doc.sampleFileName}`);
  lines.push('');
  lines.push('DESCRIPTION');
  lines.push('-'.repeat(60));
  lines.push(doc.description);
  lines.push('');
  lines.push('SAMPLE FIELDS TO CAPTURE');
  lines.push('-'.repeat(60));
  doc.sampleFields.forEach((f, i) => {
    lines.push(`${String(i + 1).padStart(2, '0')}. ${f.label}${f.hint ? `  (${f.hint})` : ''}`);
  });
  lines.push('');
  lines.push('FILLING GUIDELINES');
  lines.push('-'.repeat(60));
  doc.tips.forEach((t) => lines.push(`• ${t}`));
  lines.push('');
  lines.push('Generated by Study Abroad CRM — for internal training and reference only.');
  lines.push('Always verify current requirements on the official mission / awarding body portal.');
  return lines.join('\n');
};

export const buildChecklistText = (
  category: ResourceCategory,
  docs: DocumentSample[],
  country: DestinationFilter
): string => {
  const lines: string[] = [];
  lines.push('STUDY ABROAD CRM — SECTION DOCUMENT CHECKLIST');
  lines.push('='.repeat(60));
  lines.push(`Section     : ${category.toUpperCase()}`);
  lines.push(`Destination : ${country}`);
  lines.push(`Documents   : ${docs.length}`);
  lines.push(`Generated   : ${new Date().toLocaleString('en-GB')}`);
  lines.push('');
  RESOURCE_GROUPS[category].forEach((group) => {
    const groupDocs = docs.filter((d) => d.group === group.id);
    if (groupDocs.length === 0) return;
    lines.push(`## ${group.label.toUpperCase()} (${groupDocs.length})`);
    groupDocs.forEach((d) => {
      lines.push(`   [ ] ${d.name} — ${d.requirement}${d.processingTime ? ` • ${d.processingTime}` : ''}`);
    });
    lines.push('');
  });
  lines.push('Always verify current requirements on the official mission / awarding body portal.');
  return lines.join('\n');
};

